"""make host-secrets: the parameters of the AWS host below /gbmi/prod/ (week 3 plan 3.3, D43).

The host reads its secrets from Parameter Store (compose/host/render_env.sh). Terraform manages
no parameter, so no secret stands in the Terraform state. The script creates the entries from
the laptop:

    python tools/host_secrets.py create       create each missing entry; never overwrite one
    python tools/host_secrets.py list         the names, the types and the last changes
    python tools/host_secrets.py sec-source off|live
                                              the source of the SEC client of the host

``create`` makes one SecureString entry for each generated secret of ``.env.example``, with a new
value which is generated in memory, and one for the declared identity for the SEC, which is
copied from the git-ignored ``.env`` of the laptop. An entry which exists stays as it is: a new
database password would lock out a stack which is already initialised.

The script prints names only, never a value, and no error text of AWS which could quote one.
The credentials come from the environment (the profile ``gbmi`` of ``aws login``).
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "compose"))

import make_env  # noqa: E402  (compose/make_env.py: the generator of the laptop's .env)

PREFIX = "/gbmi/prod/"
USER_AGENT = "GBMI_SEC_USER_AGENT"
SEC_SOURCE = "GBMI_SEC_SOURCE"
#: The line of the Makefile which gives the working stack of the laptop its SEC source.
_WORKING_SOURCE = re.compile(r"^SEC_SOURCE := (\w+)$", re.MULTILINE)


def out(text: str) -> None:
    sys.stdout.write(text + "\n")


def generated_names(example: Path) -> dict[str, str]:
    """Each generated secret of the template with its placeholder, in the order of the file."""
    placeholders = (make_env.GENERATE, make_env.GENERATE_FERNET)
    return {
        name: value for name, value in make_env.parse(example.read_text("utf-8")).items()
        if value in placeholders
    }  # fmt: skip


def user_agent(env_file: Path) -> str | None:
    """The declared identity for the SEC from the .env of the laptop, without its quotes."""
    if not env_file.is_file():
        return None
    value = make_env.parse(env_file.read_text("utf-8")).get(USER_AGENT, "").strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        value = value[1:-1]
    return value or None


def existing(client: Any) -> dict[str, dict[str, Any]]:
    """The entries below the prefix by their short name; the values are not asked for."""
    found: dict[str, dict[str, Any]] = {}
    pages = client.get_paginator("describe_parameters").paginate(
        ParameterFilters=[{"Key": "Name", "Option": "BeginsWith", "Values": [PREFIX]}]
    )
    for page in pages:
        for parameter in page["Parameters"]:
            found[parameter["Name"].removeprefix(PREFIX)] = parameter
    return found


def put(client: Any, name: str, value: str, *, kind: str, overwrite: bool, description: str) -> str:
    """Write one entry; give "created", "updated" or the kind of the error, never its text."""
    try:
        client.put_parameter(
            Name=PREFIX + name, Value=value, Type=kind, Overwrite=overwrite, Description=description
        )
    except Exception as error:  # the text of an error of AWS can quote the request
        code = getattr(error, "response", {}).get("Error", {}).get("Code") or type(error).__name__
        return f"FAILED ({code})"
    return "updated" if overwrite else "created"


def create(client: Any, *, example: Path, env_file: Path) -> int:
    present = existing(client)
    failures = 0
    for name, placeholder in generated_names(example).items():
        if name in present:
            out(f"exists   {name}")
            continue
        result = put(
            client,
            name,
            make_env.generate(placeholder),
            kind="SecureString",
            overwrite=False,
            description="Generated by make host-secrets; read by the AWS host only.",
        )
        failures += result.startswith("FAILED")
        out(f"{result:<8} {name}")
    if USER_AGENT in present:
        out(f"exists   {USER_AGENT}")
    else:
        identity = user_agent(env_file)
        if identity is None:
            out(f"skipped  {USER_AGENT}: the .env of the laptop holds no value")
        else:
            result = put(
                client,
                USER_AGENT,
                identity,
                kind="SecureString",
                overwrite=False,
                description="The declared identity of requests to the SEC; copied from the laptop.",
            )
            failures += result.startswith("FAILED")
            out(f"{result:<8} {USER_AGENT}")
    return 1 if failures else 0


def listing(client: Any) -> int:
    present = existing(client)
    for name in sorted(present):
        entry = present[name]
        changed = entry.get("LastModifiedDate")
        stamp = changed.strftime("%Y-%m-%d %H:%M UTC") if changed is not None else ""
        out(f"{name:<28} {entry.get('Type', ''):<13} {stamp}")
    out(f"{len(present)} entries below {PREFIX}")
    return 0


def sec_source(client: Any, value: str, *, makefile: Path) -> int:
    """Set the source of the SEC client of the host: off, or live under two conditions."""
    if value == "live":
        # One user, one source of requests: the laptop has to be off first (change C22).
        sources = _WORKING_SOURCE.findall(makefile.read_text("utf-8"))
        current = sources[0] if sources else "unknown"
        if current != "off":
            out(
                f"refused: the working stack of the laptop has the SEC source '{current}' in "
                "the Makefile; set it to off first"
            )
            return 1
        if USER_AGENT not in existing(client):
            out(f"refused: the entry {USER_AGENT} is missing; run make host-secrets first")
            return 1
    result = put(
        client,
        SEC_SOURCE,
        value,
        kind="String",
        overwrite=True,
        description="The source of the SEC client of the AWS host: off or live.",
    )
    out(f"{result:<8} {SEC_SOURCE} = {value} (takes effect at the next start or deployment)")
    return 1 if result.startswith("FAILED") else 0


def main(arguments: list[str] | None = None, *, client: Any | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("create")
    commands.add_parser("list")
    commands.add_parser("sec-source").add_argument("value", choices=["off", "live"])
    parser.add_argument("--example", type=Path, default=REPO / ".env.example")
    parser.add_argument("--env", type=Path, default=REPO / ".env")
    parser.add_argument("--makefile", type=Path, default=REPO / "Makefile")
    options = parser.parse_args(arguments)
    if client is None:
        import boto3

        client = boto3.client("ssm")
    if options.command == "create":
        return create(client, example=options.example, env_file=options.env)
    if options.command == "list":
        return listing(client)
    return sec_source(client, options.value, makefile=options.makefile)


if __name__ == "__main__":
    sys.exit(main())
